function createStatDisplayNames(weaponConditions, stanceLabels) {
    const names = { ...BASE_STAT_DISPLAY_NAMES };
    Object.entries(weaponConditions).forEach(([id, line]) => { names[id] = `${stanceLabels[line.stance]} 사용 시 ${names[line.stat].replace(' 증가', '')}`; });
    return names;
}


