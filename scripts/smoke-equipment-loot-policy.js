const assert=require('assert');
const {prepare}=require('./audit-combat-20260905');
const {runtime:r,state,run}=prepare();
const policy=r.equipmentLootPolicy;
const item=(id,stats=[],rarity='rare')=>({id,name:'검사 장비 '+id,slot:'반지',rarity,tier:8,hiddenTier:8,baseStats:[],stats});
const filter={enabled:true,slot:'any',scope:'explicit',minMatches:1,rules:[{statId:'flatHp',minValue:50,minTier:6}]};
state.settings.equipmentTargets=policy.normalizeTargets(filter);
const desired=item(801,[{id:'flatHp',val:50,tier:6}]);
assert(policy.matches(desired));
assert(!policy.matches(item(802,[{id:'flatHp',val:49,tier:6}])));
assert(!policy.matches(item(803,[{id:'flatHp',val:50,tier:5}])));
assert(!policy.matches(item(804,[{id:'flatHp',val:30,tier:8},{id:'flatHp',val:30,tier:8}])),'separate lines are not added');
assert(policy.matches(item(805,[{id:'flatDmg',val:10,tier:6,extraStats:[{id:'flatHp',val:50}]}])),'compound extras inherit the option tier');
const implicit=item(806);implicit.baseStats=[{id:'flatHp',val:80,tier:8}];
assert(!policy.matches(implicit));
state.settings.equipmentTargets.scope='all';assert(policy.matches(implicit));
state.settings.equipmentTargets.slot='무기';assert(!policy.matches(desired));
state.settings.equipmentTargets=policy.normalizeTargets({...filter,minMatches:2,rules:[...filter.rules,{statId:'aspd',minValue:10,minTier:1}]});
assert(!policy.matches(desired));
assert(policy.matches(item(807,[...desired.stats,{id:'aspd',val:10,tier:1}])));
assert.strictEqual(policy.normalizeTargets({enabled:true,rules:[{statId:'flatHp',minValue:null,minTier:0}]}).rules.length,0);
assert.strictEqual(policy.normalizeTargets({enabled:true,rules:[{statId:'not-a-stat',minValue:0,minTier:0}]}).rules.length,0);
assert.strictEqual(policy.normalizeTargets({...filter,rules:[...filter.rules,...filter.rules]}).rules.length,1);
state.settings.equipmentTargets=policy.normalizeTargets(filter);
state.settings.autoEquipEmptySlots=false;
state.settings.itemFilterEnabled=true;
state.settings.itemFilterRarities.rare=false;
state.settings.autoSalvageEnabled=true;state.settings.autoSalvageRarities.rare=true;
state.isBackgroundCalculation=true;
const beforeCurrency=state.currencies.formlessDew;
assert.strictEqual(r.addItemToInventory(desired),true,'target overrides pickup and automatic salvage');
assert(state.inventory.some(row=>row.id===desired.id));
assert.strictEqual(state.currencies.formlessDew,beforeCurrency);
assert.strictEqual(r.isBulkSalvageProtectedItem(desired),true);
assert.strictEqual(r.addItemToInventory(item(808)),false,'unwanted item still follows the old filter');
state.inventory.push(item(820, desired.stats, 'magic'), item(821, [], 'magic'));
r.bulkSalvage('magic');
assert(state.inventory.some(row=>row.id===820),'actual bulk salvage retains a target');
assert(!state.inventory.some(row=>row.id===821),'actual bulk salvage removes unwanted equipment');
const restored=r.mergeDefaults(JSON.parse(r.serializeSaveState(state)));
assert(policy.matches(desired,restored),'target settings survive save/reload');
assert.strictEqual(r.mergeDefaults({}).settings.equipmentTargets.enabled,false,'old saves gain no active automation');
state.offlineProgress.stashLevel=1;
state.offlineProgress.stash=[];
const stashed=item(809,desired.stats);
assert.strictEqual(r.addItemToInventory(stashed),true);
assert(state.offlineProgress.stash.some(row=>row.id===809 && row.offlineProtected),'target is protected in the offline stash');

const before=JSON.parse(r.serializeSaveState(state));
const after=JSON.parse(JSON.stringify(before));
after.inventory.push(item(810,desired.stats));
after.inventory.push(item(811,[],'unique'));
after.offlineProgress.stash.push(item(812,desired.stats));
after.equipment['반지1']=item(813,[],'unique');
const original=JSON.stringify({before,after});
const highlights=policy.collectHighlights(before,after);
assert.strictEqual(highlights.total,4,'includes new inventory, stash and equipped items');
assert(highlights.items.some(row=>row.id===812 && row.location==='방치 보관함'));
assert(!highlights.items.some(row=>row.id===801),'existing items cannot appear as new rewards');
assert.strictEqual(highlights.items[0].reason,'목표 옵션 일치');
assert.strictEqual(JSON.stringify({before,after}),original,'summary classification is read-only');
for(let id=830;id<838;id++) after.inventory.push(item(id,desired.stats));
assert.strictEqual(policy.collectHighlights(before,after).total,12);
assert.strictEqual(policy.collectHighlights(before,after).items.length,5,'return summary caps visual detail without losing the total');
assert.strictEqual(policy.highlight(item(900),state),null,'ordinary rare drops do not all receive a major celebration');

state.offlineProgress.stashLevel=0;state.inventory=[];state.settings.itemFilterEnabled=false;state.isBackgroundCalculation=false;
r.Math.random=()=>0.5;
const probe=r.generateEquipmentDrop({isBoss:true});
const option=probe.stats[0];
state.settings.equipmentTargets=policy.normalizeTargets({...filter,rules:[{statId:option.id,minValue:0,minTier:0}]});
run('battleFx.length=0;rollEquipmentLoot({id:777,isBoss:true},getZone(1),1)');
assert(run('battleFx.some(fx=>fx.type==="lootCelebration" && fx.reason==="목표 옵션 일치" && fx.itemName)'),'real drop dispatch includes the reason and item name');
console.log('smoke-equipment-loot-policy passed');
