'use strict';
const assert = require('assert');
const vm = require('vm');
const {buildGameRuntime} = require('./lib/game-runtime');
const context = buildGameRuntime();
const run = code => vm.runInContext(code, context);
const plain = code => JSON.parse(run(`JSON.stringify(${code})`));

run(`game.passives=[]; game.activeSkill='기본 공격';
    game.equipment['갑옷']={id:9001, name:'검증 갑옷', slot:'갑옷', rarity:'normal', baseStats:[], stats:[{id:'spellPctDmg',val:100}]};`);
const attack = run('getPlayerStats()');
assert.ok(attack.sSkill.tags.includes('attack'));
context.affixStats=attack;
assert.ok(run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('spellPctDmg')"));
assert.ok(!run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('attackPctDmg')"));
assert.strictEqual(run('equipmentInspectionUi.getInactiveAffixIds(null).size'),0);
assert.strictEqual(run("equipmentInspectionUi.getInactiveAffixIds(affixStats,['소환수']).size"),0);
run("game.passives=['n2c51dapljo']");
const duel = run('getPlayerStats()');
context.affixStats=duel;
assert.ok(!run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('spellPctDmg')"));
assert.ok(run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('spellLeech')"));
assert.ok(duel.damageIncreasePct >= attack.damageIncreasePct + 100);
assert.deepStrictEqual(Array.from(duel.sSkill.tags), Array.from(attack.sSkill.tags), 'sharing damage must not turn an attack into a spell');
run(`game.activeSkill=Object.keys(SKILL_DB).find(key=>SKILL_DB[key].tags.includes('spell'));
    game.skills.push(game.activeSkill); game.passives=[];`);
const spell = run('getPlayerStats()');
context.affixStats=spell;
assert.ok(run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('attackPctDmg')"));
assert.ok(run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('leech')"));
assert.ok(!run("equipmentInspectionUi.getInactiveAffixIds(affixStats).has('spellLeech')"));
run("game.passives=['n2c51dapljo']");
assert.strictEqual(run('getPlayerStats().damageIncreasePct'), spell.damageIncreasePct, 'spell increases must not count twice');

run(`game.activeSkill='기본 공격'; game.passives=[];
    game.equipment['갑옷'].stats=[{id:'bleedChance',val:100}];`);
const normal = run('getPlayerStats()');
run("game.passives=['pt_warrior_blood_cradle']");
const cradle = run('getPlayerStats()');
assert.strictEqual(cradle.bleedChance, normal.bleedChance * 0.7);
context.stats = cradle;
assert.strictEqual(run("getPlayerAilmentProcChance(stats,'bleed',false,1)"), 0.7);
assert.strictEqual(run("getPlayerAilmentProcChance(stats,'bleed',true,0)"), 0.175);
assert.strictEqual(run("getSkillAilmentStats({...stats,sSkill:{ailmentChanceBonus:{bleed:20}}},'phys',null).bleedChance"), cradle.bleedChance + 14);
run(`Math.random=()=>0; enemy={id:999,hp:100000,maxHp:100000,ailments:[]};
    for(let i=0;i<9;i++) applyEnemyAilmentFromHit(enemy,stats,1000,false,{primaryAilmentChance:1});`);
assert.strictEqual(run("enemy.ailments.find(row=>row.type==='bleed').stacks"), 5);
context.normalStats = normal;
assert.strictEqual(run("getEnemyDamageAilmentDps(enemy.ailments[0],stats,enemy)"),
    Math.floor(run("getEnemyDamageAilmentDps(enemy.ailments[0],normalStats,enemy)") * 0.7));
assert.strictEqual(run("getEnemyDamageAilmentMaxStacks('poison',stats)"), 1);
run(`game.ascendClass='catalyst'; game.ascendKeystones=['ct6','ct8'];`);
assert.strictEqual(run("getEnemyDamageAilmentMaxStacks('bleed',stats)"), 5);
run(`game.ascendClass=''; game.ascendKeystones=[];
    fresh={id:998,hp:100000,maxHp:100000,ailments:[]};
    for(let i=0;i<9;i++) applyEnemyAilmentFromHit(fresh,normalStats,1000,false,{primaryAilmentChance:1});`);
assert.strictEqual(run('fresh.ailments[0].stacks'), 1);

run(`game.passives=[]; game.passivePoints=100; game.startNode='pt_start_warrior';
    game.discoveredPassives=Object.keys(PASSIVE_TREE.nodes);
    weapon={id:9002,name:'검증 검',slot:'무기',rarity:'normal',baseStats:[],stats:[]};
    game.equipment['무기']=weapon; saveEquipmentLoadoutPreset(0,'무기 세팅');`);
assert.strictEqual(run("activatePassivePath('n39ip40yc3d').activated"), true);
assert.strictEqual(run("game.equipment['무기']"), null);
assert.strictEqual(run('game.inventory.filter(item=>item===weapon).length'), 1);
assert.deepStrictEqual(plain('getEquipCandidateSlots(weapon)'), []);
assert.strictEqual(run('equipItemById(9002)'), false);
assert.strictEqual(run('tryAutoEquipEmptySlot(weapon)'), null);
const inventory = plain('game.inventory');
assert.strictEqual(run('applyEquipmentLoadoutPreset(0).ok'), false);
assert.deepStrictEqual(plain('game.inventory'), inventory);
run(`game.equipment['무기']=weapon; game.inventory=game.inventory.filter(item=>item!==weapon);
    restored=mergeDefaults(JSON.parse(JSON.stringify(game)));`);
assert.strictEqual(run("restored.equipment['무기']"), null);
assert.strictEqual(run('restored.inventory.filter(item=>item.id===9002).length'), 1);
run(`restricted={passives:['n39ip40yc3d'], inventory:Array.from({length:120},(_,id)=>({id:id+10000,slot:'갑옷'})),
    equipment:{'무기':weapon,'방패':{...weapon,id:9003},'갑옷':game.equipment['갑옷']}};`);
assert.strictEqual(run('enforcePassiveEquipmentRestrictions(restricted)'), 2);
assert.strictEqual(run('restricted.inventory.length'), 122, 'full inventory must not destroy either weapon');
assert.strictEqual(run('enforcePassiveEquipmentRestrictions(restricted)'), 0, 'reconciliation must not duplicate weapons');
assert.strictEqual(run("restricted.equipment['갑옷'] === game.equipment['갑옷']"), true);
assert.deepStrictEqual(plain('getEquipCandidateSlots(weapon,restricted)'), []);
run("game.passives=[]");
assert.strictEqual(run("canEquipItemToSlot(weapon,'무기')"), true);
assert.strictEqual(run("PASSIVE_TREE.nodes.n39ip40yc3d.desc.includes('공격력')"), false);
assert.ok(run("getPassiveActivationPath('pt_warrior_blood_cradle').includes('pt_spine_warrior_left_07')"));
console.log('smoke-warrior-keystone-rules passed');
