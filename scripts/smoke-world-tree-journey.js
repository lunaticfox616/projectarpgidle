const assert=require('node:assert/strict');
const vm=require('node:vm');
const {buildGameRuntime}=require('./lib/game-runtime');
const r=buildGameRuntime(),run=code=>vm.runInContext(code,r);
r.showGameToast=()=>{};
run("game=mergeDefaults({});window.game=game;game.season=10;game.currentZoneId=0;game.combatHalted=true");
assert(run("worldTreeJourney.lockReason(game,'worldtree_root')"));
run("worldTreeJourneyUi.travel()");
assert.equal(r.game.currentZoneId,0,'locked travel changes nothing');
run("game.loopProgressCurrent.chaos20Cleared=true;game.chaosRealm.unlocked=true;contentProgression.sync();game.settings.mapCompleteAction='nextZone'");
assert.equal(run("worldTreeJourney.lockReason(game,'worldtree_root')"),null);
assert(run("worldTreeJourney.lockReason(game,'worldtree_guardian')"),'guardian cannot bypass earlier maps');
const seed=run('game.worldTreeJourney.seed');
const chart=run("JSON.stringify(WORLD_TREE_JOURNEY.nodes.map(n=>getZone(n.id)))");
run("game=mergeDefaults(JSON.parse(JSON.stringify(game)));window.game=game");
assert.equal(run('game.worldTreeJourney.seed'),seed);
assert.equal(run("JSON.stringify(WORLD_TREE_JOURNEY.nodes.map(n=>getZone(n.id)))"),chart,'reload cannot reroll the chart');
assert.notEqual(run("getZone('worldtree_grove').worldTreeKind"),run("getZone('worldtree_breach').worldTreeKind"));
assert.notEqual(run("getZone('worldtree_crossing').worldTreeKind"),run("getZone('worldtree_meteor').worldTreeKind"));
run("worldTreeJourneyUi.select('worldtree_breach');worldTreeJourneyUi.select('worldtree_meteor')");
const route=Array.from(run("worldTreeJourney.pathTo(game,'worldtree_guardian')"));
assert.deepEqual(route,['worldtree_root','worldtree_breach','worldtree_meteor','worldtree_guardian']);
run("worldTreeJourneyUi.configure('risk',2)");
const risk=run("getZone('worldtree_root')");
assert.equal(risk.mapHpMul,1.8);assert.equal(risk.mapDamageMul,1.3);
for(const kind of ['grove','breach','meteor','boss']){
    const waves=run("worldTreeJourney.encounterPlan({...getZone('worldtree_root'),worldTreeKind:"+JSON.stringify(kind)+"})");
    assert.equal(waves.filter(w=>w.boss).length,1,'each map ends with exactly one boss');
    assert(waves.every(w=>w.count<=10),'bounded enemy pack size');
}
run("worldTreeJourneyUi.travel()");
assert.equal(r.game.currentZoneId,'worldtree_root');
assert.equal(r.game.worldTreeJourney.unlocked,true);
run("worldTreeJourneyUi.configure('risk',0);worldTreeJourneyUi.stage(2)");
assert.equal(r.game.worldTreeJourney.risk,2,'risk cannot change during combat');
assert.equal(r.game.worldTreeJourney.stage,1);
run("worldTreeJourneyUi.pause();finishEncounterRun()");
assert.equal(r.game.combatHalted,true);
assert.equal(r.game.worldTreeJourney.notice.kind,'paused');
const count=run('game.worldTreeJourney.cleared.length');
const wallet=JSON.stringify(r.game.currencies);
run("finishEncounterRun()");
assert.equal(run('game.worldTreeJourney.cleared.length'),count);
assert.equal(JSON.stringify(r.game.currencies),wallet,'duplicate finish cannot pay twice');
run("game=mergeDefaults(JSON.parse(JSON.stringify(game)));window.game=game;worldTreeJourneyUi.resume()");
assert.equal(r.game.currentZoneId,'worldtree_breach');
assert.deepEqual(Array.from(r.game.worldTreeJourney.queue),['worldtree_meteor','worldtree_guardian']);
run("game=mergeDefaults(JSON.parse(JSON.stringify(game)));window.game=game");
assert.equal(r.game.worldTreeJourney.active.id,'worldtree_breach');
run("worldTreeJourney.fail(game,getZone(game.currentZoneId))");
assert.equal(r.game.worldTreeJourney.notice.kind,'defeat');
run("game=mergeDefaults(JSON.parse(JSON.stringify(game)));window.game=game;worldTreeJourneyUi.resume()");
assert.equal(r.game.currentZoneId,'worldtree_breach','retry preserves chosen branch');
run("finishEncounterRun();finishEncounterRun();finishEncounterRun()");
assert.equal(r.game.worldTreeJourney.notice.kind,'guardian');
assert.equal(run('worldTreeJourney.unlockedStage(game)'),2);
assert.equal(r.game.worldTreeJourney.loopClear.stage,1,'future loop gate has a per-loop completion ledger');
assert.equal(run('getSeasonAbyssDepthCap(10)'),20,'existing loop progression is unchanged in the scaffold');
assert.equal(run("worldTreeJourney.lockReason(game,'worldtree_guardian')").includes('마친'),true);
run("worldTreeJourneyUi.nextStage()");
assert.equal(r.game.worldTreeJourney.stage,2);assert.equal(r.game.worldTreeJourney.cycle,1);
assert.equal(r.game.worldTreeJourney.cleared.length,0);
const fresh=run("JSON.stringify(getZone('worldtree_root'))");
run("worldTreeJourneyUi.stage(1);worldTreeJourneyUi.stage(2)");
assert.equal(run("JSON.stringify(getZone('worldtree_root'))"),fresh,'tier switching cannot reroll');
run("worldTreeJourneyUi.travel();finishEncounterRun();worldTreeJourneyUi.pause();finishEncounterRun();worldTreeJourneyUi.stage(1)");
assert.equal(r.game.worldTreeJourney.stage,2,'an unfinished chart cannot be rerolled');
