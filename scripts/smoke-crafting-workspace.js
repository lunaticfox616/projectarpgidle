const assert = require('node:assert/strict');
const vm = require('node:vm');
const {buildGameRuntime} = require('./lib/game-runtime');
const ctx = buildGameRuntime();
const run = code => vm.runInContext(code,ctx);
const plain = code => JSON.parse(JSON.stringify(run(code)));
assert.equal(run("craftingWorkspaceState.group('condensedSkyPower')"),'');
assert.equal(run("craftingWorkspaceState.group('rivalKey')"),'');
assert.equal(run("craftingWorkspaceState.group('cosmosSovereignKey')"),'');
assert.equal(run("craftingWorkspaceState.group('fossilJagged')"),'fossil');
run("game=cloneDefaultGame();game.currencies.formlessDew=2;craftingWorkspaceState.capture(game);game.currencies.formlessDew=0;");
assert.ok(plain('game.craftingWorkspace.discovered').includes('formlessDew'));
assert.ok(!plain('game.craftingWorkspace.discovered').includes('fairyRing'));
run("game.craftingWorkspace.pins=['blightSpore','sapBud','goldenRule','formlessDew'];this.saved=mergeDefaults(JSON.parse(serializeSaveState()));");
assert.deepEqual(plain('saved.craftingWorkspace.pins'),['blightSpore','sapBud','goldenRule','formlessDew']);
assert.ok(plain('saved.craftingWorkspace.discovered').includes('formlessDew'));
const damaged = plain("craftingWorkspaceState.normalize({discovered:['bad','fossilJagged','fossilJagged'],pins:['bad','fossil'],goal:{statId:4,minTier:Infinity}}, {magicBud:1,fairyRing:0})");
assert.deepEqual(damaged.discovered,['fossilJagged','magicBud']);
assert.equal(damaged.pins.length,4);assert.equal(new Set(damaged.pins).size,4);
assert.deepEqual(damaged.goal,{statId:'',minTier:0});
run("this.weapon=createItemFromBase(BASE_ITEM_DB.find(row=>row.slot==='무기'),'rare',12);weapon.stats=[];this.recipe={key:'formlessDew',kind:'reroll'};");
assert.ok(plain("craftingGoalOptions.get(weapon,recipe,'none')").length>0);
assert.deepEqual(plain("craftingGoalOptions.get(weapon,{key:'magicBud',kind:'reroll'},'none')"),[]);
run("weapon.stats=Array.from({length:6},(_,i)=>({id:'locked'+i,lockedByHoney:true}));");
assert.deepEqual(plain("craftingGoalOptions.get(weapon,recipe,'none')"),[]);
assert.deepEqual(plain("craftingGoalOptions.get(null,recipe,'none')"),[]);
assert.equal(plain("mergeDefaults({itemSubtab:'item-tab-fossil'}).itemSubtab"),'item-tab-craft');
run("weapon.stats=[];");
assert.ok(plain("craftingGoalOptions.get(weapon,{key:'fossilOld',kind:'fossil'},'none')").length>0);
assert.ok(plain("craftingGoalOptions.get(weapon,{key:'fossilRift',kind:'fossil'},'none')").length>0);
run("weapon.stats=[{id:'fireFlatDmg',lockedByHoney:true,craftSource:'fossil'}];");
assert.deepEqual(plain("craftingGoalOptions.get(weapon,{key:'fossilJagged',kind:'fossil'},'none')"),[]);
console.log('smoke-crafting-workspace passed');
