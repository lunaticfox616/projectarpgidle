// Map receipts (js/combat-loot-receipts.js): while an atlas map is open, committed combat loot is recorded for display only;
// crafting/trade gains are not, a failed capture still closes, the receipt survives saves, completion and deaths, and the
// next map starts a fresh one.
const assert=require('node:assert/strict');
const vm=require('node:vm');
const {buildGameRuntime}=require('./lib/game-runtime');
const runtime=buildGameRuntime();
const run=source=>vm.runInContext(source,runtime);
runtime.showGameToast=()=>{};
run(`game=mergeDefaults({});window.game=game;game.season=10;game.maxZoneId=29;game.currentZoneId=29;
    game.chaosRealm.unlocked=true;game.loopProgressCurrent.chaos20Cleared=true;
    contentProgression.sync();contentProgression.purchase('craft',game);
    game.settings.autoEquipEmptySlots=false;game.settings.autoSalvageEnabled=false;
    atlas.sync(game);atlasRun.open(game.atlas.stash[0].uid);`);
assert.equal(runtime.game.currentZoneId,'atlas_map');
const before=runtime.game.currencies.magicBud;
run(`combatLootReceipts.capture(game,()=>awardCurrency('magicBud',3,'drop'));`);
assert.equal(runtime.game.currencies.magicBud,before+3);
assert.equal(runtime.game.explorationLoot.currencies.magicBud,3);
run(`awardCurrency('magicBud',7);`);
assert.equal(runtime.game.explorationLoot.currencies.magicBud,3,'craft/trade rewards outside combat capture are excluded');
assert.throws(()=>run(`combatLootReceipts.capture(game,()=>{awardCurrency('magicBud',2);throw new Error('loot failure')})`),/loot failure/);
run(`awardCurrency('magicBud',5);`);
assert.equal(runtime.game.explorationLoot.currencies.magicBud,5,'committed rewards survive failure; capture always closes');
run(`combatLootReceipts.capture(game,()=>{
    for(let i=0;i<7;i++)addItemToInventory(createItemFromBase(BASE_ITEM_DB[0],'rare',3));
});`);
assert.equal(runtime.game.explorationLoot.equipmentCount,7);
assert.equal(runtime.game.explorationLoot.items.length,3,'receipt metadata stays bounded');
run(`game.settings.autoSalvageEnabled=true;game.settings.autoSalvageRarities.rare=true;
    combatLootReceipts.capture(game,()=>addItemToInventory(createItemFromBase(BASE_ITEM_DB[0],'rare',3)));`);
assert.equal(runtime.game.explorationLoot.equipmentCount,7,'auto-salvaged equipment is not presented as retained loot');
run(`game=mergeDefaults(JSON.parse(JSON.stringify(game)));window.game=game;`);
assert.equal(runtime.game.explorationLoot.currencies.magicBud,5);
assert.equal(runtime.game.explorationLoot.items.length,3);
const receipt=JSON.stringify(runtime.game.explorationLoot);
run(`game.settings.showDeathNotice=false;handlePlayerDefeat(getZone(game.currentZoneId),getPlayerStats(),'test',{noToast:true});`);
assert.equal(runtime.game.atlas.run.portals,2);
assert.equal(JSON.stringify(runtime.game.explorationLoot),receipt,'a death inside the map keeps the map receipt');
const wallet=JSON.stringify(runtime.game.currencies);
run(`atlasRun.finish(getZone(game.currentZoneId));`);
assert.equal(runtime.game.atlas.lastResult.outcome,'complete');
assert.equal(JSON.stringify(runtime.game.explorationLoot),receipt,'completion keeps the receipt for the result view');
assert.equal(JSON.stringify(runtime.game.currencies),wallet,'receipt completion never grants rewards');
run(`combatLootReceipts.capture(game,()=>awardCurrency('magicBud',4,'drop'));`);
assert.equal(JSON.stringify(runtime.game.explorationLoot),receipt,'outside a map nothing is recorded');
run(`game.currentZoneId=29;atlasRun.open(game.atlas.stash[0].uid);`);
assert.equal(runtime.game.explorationLoot.equipmentCount,0,'the next map resets display only');
run(`game.explorationLoot={currencies:{fake:20,magicBud:Infinity,sapBud:-2},items:[null,{}, {id:'bad',name:'bad',rarity:'unique',slot:'무기'}],equipmentCount:Infinity};
    combatLootReceipts.normalize(game);`);
assert.equal(Object.keys(runtime.game.explorationLoot.currencies).length,0);
assert.equal(runtime.game.explorationLoot.items.length,0);
assert.equal(runtime.game.explorationLoot.equipmentCount,0);
console.log('smoke-exploration-loot-receipts passed');
