const assert = require('assert');
const vm = require('vm');
const { buildGameRuntime } = require('./lib/game-runtime');
const context = buildGameRuntime();
vm.runInContext(`game = JSON.parse(JSON.stringify(defaultGame));
    game.level = 63; game.loopKills = 456; game.currencies.magicBud = 17;
    game.records = createDefaultRecordsState(Date.now());
    ensureRecordsState(); game.records.currentLoop.activeMs = 3600000;
    game.enemies = [{ id: 'old-enemy' }];
    handleSeasonLoopConditionMet();`, context);
const state = () => JSON.parse(vm.runInContext('JSON.stringify(game)', context));
let first = state();
assert.strictEqual(first.season, 1, 'settlement must wait for the player before resetting');
assert.strictEqual(first.pendingLoopReady, true);
assert.strictEqual(first.pendingLoopDecision, false, 'early loops do not offer continued hunting');
assert.strictEqual(first.combatHalted, true);
assert.deepStrictEqual(first.enemies, []);
assert.strictEqual(first.currencies.magicBud, 17);
assert.strictEqual(vm.runInContext('isTutorialPresentationBlocked()', context), true, 'unlock guides must wait until mandatory loop choices finish');
let summary = vm.runInContext('loopSettlementUi.summaryHtml()', context);
assert(summary.includes('63') && summary.includes('456') && summary.includes('1시간 0분'));
assert(summary.includes(`해금 포인트 +${context.CONTENT_UNLOCK_POINTS_PER_LOOP}`) && summary.includes('직접 선택'), 'settlement must show the actual unlock point award');
vm.runInContext('handleSeasonLoopConditionMet()', context);
assert.deepStrictEqual(state(), first, 'a duplicate completion must not grant or clear progress twice');
vm.runInContext(`game.season = 10; game.abyssEndlessDepth = 20;
    game.loopProgressCurrent.chaos20Cleared = true;
    game.loopProgressCurrent.bestAbyssDepth = 20;
    handleSeasonLoopConditionMet();`, context);
let later = state();
assert.strictEqual(later.season, 10, 'later completion must also show settlement before a reset');
assert.strictEqual(later.pendingLoopReady, false);
assert.strictEqual(later.pendingLoopDecision, true);
vm.runInContext('chooseLoopAdvance(false)', context);
assert.strictEqual(state().season, 10);
assert.strictEqual(state().pendingLoopDecision, false);
assert.strictEqual(state().abyssEndlessDepth, 21, 'deferring follows the existing next-depth progression');
assert.strictEqual(state().currencies.magicBud, 17);
console.log('smoke-loop-settlement passed');
