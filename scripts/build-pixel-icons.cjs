#!/usr/bin/env node
/* 원화 아이콘(장비·젬·재화)을 도트 사본으로 다시 찍는다. 원본은 그대로 두고 assets/px/ 아래에 같은 경로로 쓴다.
 *
 *   node scripts/build-pixel-icons.cjs
 *
 * 1. 게임 데이터(ITEM_VISUAL_ASSET_DB · SKILL_GEM_ART_PATHS · CURRENCY_ICON_PATHS)가 가리키는 그림을 모은다.
 * 2. 브라우저(Playwright Chromium)로 짧은 변 32도트·긴 변 48도트를 넘지 않게 줄이고(정사각 32×32, 1×3칸 무기 16×48 —
 *    인벤토리 한 칸에 16도트 꼴), 반투명 가장자리를 끊고, 색을 단계로 묶고, 실루엣 둘레에 1도트 검은 윤곽을 두른다.
 *    이미 그보다 작은 그림(32도트 세계수 젬 등)은 건너뛴다.
 * 3. 사본 목록을 data/pixel-icons.js(PIXEL_ICON_SOURCES)로 쓴다. 화면은 js/utils.js pixelIconPath로 사본을 고른다.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const SHORT_DOTS = 32, LONG_DOTS = 48;
const manifestFile = path.join(root, 'data/pixel-icons.js');

function writeManifest(sources) {
    const lines = sources.map(source => `    ${JSON.stringify(source)}`).join(',\n');
    fs.writeFileSync(manifestFile, '// Generated by scripts/build-pixel-icons.cjs — painted icons that have a pixel copy under assets/px/.\n'
        + `const PIXEL_ICON_SOURCES = Object.freeze([\n${lines}\n]);\nsafeExposeData({ PIXEL_ICON_SOURCES });\n`);
}
function collectStrings(value, out) {
    if (typeof value === 'string') out.add(value.split('?')[0]);
    else if (value && typeof value === 'object') Object.values(value).forEach(child => collectStrings(child, out));
    return out;
}
function iconSources() {
    // The runtime loads data/pixel-icons.js itself; an empty list keeps the first build possible.
    if (!fs.existsSync(manifestFile)) writeManifest([]);
    const { buildGameRuntime } = require('./lib/game-runtime');
    const runtime = buildGameRuntime();
    const found = collectStrings(vm.runInContext('[ITEM_VISUAL_ASSET_DB, SKILL_GEM_ART_PATHS, CURRENCY_ICON_PATHS]', runtime), new Set());
    return [...found].filter(file => /^assets\/.+\.(png|webp)$/i.test(file) && fs.existsSync(path.join(root, file))).sort();
}
function copyPath(source) {
    return 'assets/px/' + source.slice('assets/'.length).replace(/\.(png|webp)$/i, '.png');
}

/** Runs in the page: returns a PNG data URL, or null when the source is already at or below the dot size. */
async function pixelateInPage({ dataUrl, shortDots, longDots }) {
    const image = await new Promise((resolve, reject) => { const img = new Image(); img.onload = () => resolve(img); img.onerror = reject; img.src = dataUrl; });
    const scale = Math.max(Math.min(image.width, image.height) / shortDots, Math.max(image.width, image.height) / longDots);
    if (scale <= 1) return null;
    const width = Math.max(1, Math.round(image.width / scale)), height = Math.max(1, Math.round(image.height / scale));
    const canvas = document.createElement('canvas');
    canvas.width = width; canvas.height = height;
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    ctx.imageSmoothingEnabled = true; ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(image, 0, 0, width, height);
    const pixels = ctx.getImageData(0, 0, width, height), data = pixels.data, solid = new Uint8Array(width * height);
    for (let i = 0; i < width * height; i++) {
        if (data[i * 4 + 3] < 110) { data[i * 4 + 3] = 0; continue; }
        solid[i] = 1; data[i * 4 + 3] = 255;
        for (let k = 0; k < 3; k++) data[i * 4 + k] = Math.min(255, Math.round(data[i * 4 + k] / 24) * 24);
    }
    const out = new Uint8ClampedArray(data);
    const touches = (x, y) => [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const nx = x + dx, ny = y + dy;
        return nx >= 0 && ny >= 0 && nx < width && ny < height && solid[ny * width + nx];
    });
    for (let y = 0; y < height; y++) {
        for (let x = 0; x < width; x++) {
            const i = y * width + x;
            if (!solid[i] && touches(x, y)) out.set([8, 6, 5, 255], i * 4);
        }
    }
    ctx.putImageData(new ImageData(out, width, height), 0, 0);
    return canvas.toDataURL('image/png');
}

async function main() {
    const sources = iconSources();
    const { chromium } = require('@playwright/test');
    const browser = await chromium.launch();
    const page = await browser.newPage();
    const made = [];
    for (const source of sources) {
        const bytes = fs.readFileSync(path.join(root, source));
        const mime = source.endsWith('.webp') ? 'image/webp' : 'image/png';
        const result = await page.evaluate(pixelateInPage, { dataUrl: `data:${mime};base64,${bytes.toString('base64')}`, shortDots: SHORT_DOTS, longDots: LONG_DOTS });
        if (!result) continue;
        const target = path.join(root, copyPath(source));
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, Buffer.from(result.split(',')[1], 'base64'));
        made.push(source);
    }
    await browser.close();
    writeManifest(made);
    console.log(`원화 ${sources.length}개 중 ${made.length}개를 도트 사본(assets/px/)으로 찍고 data/pixel-icons.js를 썼습니다.`);
}
main().catch(error => { console.error(error); process.exit(1); });
