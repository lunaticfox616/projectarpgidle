const assert = require('assert');
const { buildGameRuntime } = require('./lib/game-runtime');
const runtime = buildGameRuntime();
const game = runtime.game;
game.season = 30;
game.settings.mapCompleteAction = 'stop';
game.enemies = [];
game.underworldProgress = { highestFloor:50, currentFloor:12 };
game.skyTower.unlocked = true;
game.skyTower.highestFloor = 40;
game.skyTower.currentFloor = 8;
game.skyTower.loopSeason = 30;
game.currentZoneId = 'underworld_core';
runtime.finishEncounterRun();
assert.equal(game.loopProgressCurrent.bestUnderworldFloor,12);
assert.equal(game.underworldProgress.highestFloor,50);
game.underworldProgress.currentFloor = 3;
runtime.finishEncounterRun();
assert.equal(game.loopProgressCurrent.bestUnderworldFloor,12,'repeating lower floors preserves this-loop maximum');
game.currentZoneId = 'sky_tower';
runtime.finishEncounterRun();
assert.equal(game.loopProgressCurrent.bestSkyFloor,8);
const saved = JSON.parse(JSON.stringify(game));
const restored = runtime.mergeDefaults(saved);
assert.equal(restored.loopProgressCurrent.bestUnderworldFloor,12);
assert.equal(restored.loopProgressCurrent.bestSkyFloor,8);
delete saved.loopProgressCurrent.bestUnderworldFloor;
delete saved.loopProgressCurrent.bestSkyFloor;
const legacy = runtime.mergeDefaults(saved);
assert.equal(legacy.loopProgressCurrent.bestUnderworldFloor,null,'legacy lifetime progress cannot be presented as current-loop progress');
assert.equal(legacy.loopProgressCurrent.bestSkyFloor,null);
saved.loopProgressCurrent.bestSkyFloor = -8;
saved.loopProgressCurrent.bestUnderworldFloor = 'invalid';
const malformed = runtime.mergeDefaults(saved);
assert.equal(malformed.loopProgressCurrent.bestSkyFloor,0);
assert.equal(malformed.loopProgressCurrent.bestUnderworldFloor,null);
runtime.awardLoopProgressPoints();
assert.equal(game.loopProgressCurrent.bestUnderworldFloor,0);
assert.equal(game.loopProgressCurrent.bestSkyFloor,0);
assert.equal(game.underworldProgress.highestFloor,50);
assert.equal(game.skyTower.highestFloor,40);
console.log('loop floor progress: clears, repeat, save, legacy and reset passed');
