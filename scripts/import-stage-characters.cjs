#!/usr/bin/env node
/* 던파식 캐릭터 정리 묶음(직업 6 × 무기 자세 7, 칸 128×128, 오른쪽을 보는 가로 한 줄 시트)을 게임 자산으로 만든다.
 *
 *   node scripts/import-stage-characters.cjs <리그닌_던파식_캐릭터_정리_vX 폴더>
 *
 * 묶음의 <직업>/<직업>_규격.json(모션별 파일, 프레임 수, ms, 반복, 타격 프레임, 공용 규칙)을 읽어
 *   assets/playable/stage/<직업 id>/<무기 id>/<모션 id>.png   (그림은 그대로 복사, 이름만 영문 id)
 *   data/stage-characters.js                                  (규격)
 * 로 옮긴다. 그리는 쪽은 js/canvas-stage-actors.js, 어느 무기 자세를 들지는 낀 무기의 대분류가 정한다.
 * 그림은 한 직업 × 한 무기 묶음만 불러온다(전부 풀면 약 196MB, 한 묶음은 9MB 이하).
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const JOBS = { 방랑자: 'wanderer', 전사: 'warrior', 궁수: 'archer', 비술사: 'occultist', 연금술사: 'alchemist', 성직자: 'cleric' };
const WEAPONS = { 맨손: 'unarmed', 검방패: 'swordshield', 단검: 'dagger', 활: 'bow', 오브: 'orb', 플라스크: 'flask', 향로: 'censer' };
const MOTIONS = { 대기: 'idle', 걷기: 'walk', 공격: 'attack', 시전: 'cast', 투척: 'throw', 전용공격: 'special', 사망: 'death', 연타: 'flurry', 방패공격: 'bash' };

function fail(message) { console.error(message); process.exit(1); }

/** '공격2' → 'attack2'. Unknown names stop the import: a new motion needs an id here first. */
function motionId(name) {
    const match = /^(.+?)(\d*)$/.exec(name), base = MOTIONS[match[1]];
    if (!base) fail(`모르는 모션 이름: ${name}`);
    return base + match[2];
}

/** ms list → one number when every frame lasts the same. */
function compactMs(list) {
    return list.every(value => value === list[0]) ? list[0] : list;
}

function motionSpec(source, target) {
    const out = { frames: source['프레임'], ms: compactMs(source.ms) };
    if (source['루프']) out.loop = true;
    if ('타격프레임' in source) out.hit = [].concat(source['타격프레임']);
    if (source['그림에_이펙트']) out.fx = true;
    out.file = target;
    return out;
}

function importJob(pack, jobName, outDir) {
    const spec = JSON.parse(fs.readFileSync(path.join(pack, jobName, `${jobName}_규격.json`), 'utf8'));
    const job = JOBS[jobName], weapons = {};
    let copied = 0;
    for (const [weaponName, motions] of Object.entries(spec['무기'])) {
        const weapon = WEAPONS[weaponName];
        if (!weapon) fail(`모르는 무기 이름: ${weaponName}`);
        weapons[weapon] = {};
        fs.mkdirSync(path.join(outDir, job, weapon), { recursive: true });
        for (const [name, source] of Object.entries(motions)) {
            const id = motionId(name), target = `${job}/${weapon}/${id}.png`;
            fs.copyFileSync(path.join(pack, jobName, source['파일']), path.join(outDir, target));
            weapons[weapon][id] = motionSpec(source, target);
            copied++;
        }
    }
    return { cell: spec['칸'], feetY: spec['발바닥줄_y'], centerX: spec['가운데_x'], shared: spec['공용'], entry: { label: jobName, weapons }, copied };
}

/** The shared rules the renderer reads, as numbers: the red outline hit and the walk rate range. */
function sharedRules(shared) {
    const hit = shared['피격'], move = shared['이동'];
    return {
        hit: { outlinePx: hit['외곽선두께_px'], comboMs: 333,
            steps: hit['순서'].map(step => ({ ms: step.ms, outline: step['외곽선'] === '없음' ? null : step['외곽선'], back: step['뒤로_px'], hold: !!step['멈칫'] })) },
        move: { rateMin: move['배율_최소'], rateMax: move['배율_최대'] }
    };
}

function main() {
    const pack = process.argv[2];
    if (!pack || !fs.existsSync(pack)) fail('쓰는 법: node scripts/import-stage-characters.cjs <정리 묶음 폴더>');
    const outDir = path.join(root, 'assets/playable/stage');
    fs.rmSync(outDir, { recursive: true, force: true });
    const classes = {};
    let first = null, total = 0;
    for (const jobName of Object.keys(JOBS)) {
        const result = importJob(pack, jobName, outDir);
        first = first || result;
        if (result.cell[0] !== first.cell[0] || result.feetY !== first.feetY || result.centerX !== first.centerX) fail(`${jobName}: 칸 규격이 다른 직업과 다릅니다.`);
        classes[JOBS[jobName]] = result.entry;
        total += result.copied;
    }
    const data = { source: path.basename(pack), cell: first.cell[0], feetY: first.feetY, centerX: first.centerX, path: 'assets/playable/stage/',
        ...sharedRules(first.shared), classes };
    const header = [
        '// Generated by scripts/import-stage-characters.cjs: 던파식 캐릭터 정리 묶음의 규격(직업 6 × 무기 자세 7). 직접 고치지 말고 다시 가져온다.',
        '// 칸 128×128 가로 한 줄 시트, 0번 프레임이 왼쪽, 오른쪽을 보는 그림만(왼쪽은 좌우 반전). 발바닥 줄 feetY, 발 가운데 centerX.',
        '// motion: frames, ms(모든 프레임이 같으면 숫자 하나), loop, hit(타격 프레임들, 0부터), fx(그림에 이펙트가 같이 그려짐), file.'
    ].join('\n');
    fs.writeFileSync(path.join(root, 'data/stage-characters.js'), `${header}\nconst STAGE_CHARACTERS = Object.freeze(${JSON.stringify(data)});\nsafeExposeData({ STAGE_CHARACTERS });\n`);
    console.log(`직업 ${Object.keys(classes).length}개, 시트 ${total}장 → assets/playable/stage, data/stage-characters.js`);
}

main();
