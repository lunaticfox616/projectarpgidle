const assert = require('node:assert/strict');
const vm = require('node:vm');
const { buildGameRuntime } = require('./lib/game-runtime');
const runtime = buildGameRuntime(), run = code => vm.runInContext(code, runtime);
const json = code => JSON.parse(run(`JSON.stringify(${code})`));
assert.equal(run('UNIQUE_DB.length'), 207);
assert.equal(run('Object.keys(UNIQUE_EQUIPMENT_RULES).length'), 207);
for (const unique of json('UNIQUE_DB')) {
    runtime.uniqueName = unique.name;
    const row = json(`(() => {
        const rule = UNIQUE_EQUIPMENT_RULES[uniqueName];
        const base = BASE_ITEM_DB.find(base => base.id === rule.baseId);
        const drop = generateUniqueItem(100, null, uniqueName);
        const offer = createBlackMarketUniqueOffer(UNIQUE_DB.find(row => row.name === uniqueName), 100);
        return { rule, base, drop, offer, req: levelProgression.requirements(drop) };
    })()`);
    assert.ok(row.base, unique.name);
    assert.equal(row.base.slot, unique.slots[0], unique.name);
    assert.equal(row.drop.baseId, row.rule.baseId, unique.name);
    assert.equal(row.offer.baseId, row.rule.baseId, unique.name);
    assert.equal(row.drop.slot, row.base.slot, unique.name);
    assert.deepEqual(row.req, { level: row.rule.level, attributes: row.rule.attributes });
    assert.ok(row.req.level >= 1 && row.req.level <= 80);
    assert.ok(Object.values(row.req.attributes).every(value => value > 0 && value <= 150));
}
assert.deepEqual(json("levelProgression.requirements(generateUniqueItem(100,null,'첫 계약'))"), { level: 1, attributes: {} });
run(`game=JSON.parse(JSON.stringify(defaultGame));game.level=100;
    game.actRewardBonuses=[{stat:'intelligence',value:45}];
    var a=generateUniqueItem(100,null,'공허의 첨탑');
    var b=generateUniqueItem(100,null,'공허 제국의 인장');`);
// Identity must participate in the inspection cache even when the fixed base is shared.
run(`var sameBaseUniques=UNIQUE_DB.filter(u=>UNIQUE_EQUIPMENT_RULES[u.name].baseId==='void_loop_ring');`);
assert.ok(run('sameBaseUniques.length') >= 2);
run(`a=generateUniqueItem(100,null,sameBaseUniques[0].name);b=generateUniqueItem(100,null,sameBaseUniques[1].name);`);
assert.notDeepEqual(json('levelProgression.requirements(a)'), json('levelProgression.requirements(b)'));
const resultA = json("combatEquipmentStats.inspect(a,'반지1')");
const resultB = json("combatEquipmentStats.inspect(b,'반지1')");
assert.notDeepEqual(resultA, resultB, 'different unique gates cannot share a cached result');
run(`var old=generateUniqueItem(100,null,'타락각 투구');
    delete old.uniqueEquipmentVersion;
    old.slot='장갑';old.baseId='hide_gloves';old.baseName='legacy';old.locked=true;
    old.baseStats=[{id:'evasion',val:10,valMin:8,valMax:12,tier:0}];
    var save=JSON.parse(JSON.stringify(defaultGame));save.equipment['장갑1']=old;
    save.uniqueCodex={'장갑|타락각 투구':JSON.parse(JSON.stringify(old))};
    save.uniqueHuntTargets=['무기|핏빛 톱날'];
    var oldId=old.id;var originalAffixes=JSON.stringify(normalizeItem(JSON.parse(JSON.stringify(old))).stats);
    game=mergeDefaults(save);`);
assert.equal(run("game.equipment['장갑1']"), null);
assert.equal(run('game.inventory.filter(item=>item.id===oldId).length'), 1);
assert.equal(run('game.inventory.find(item=>item.id===oldId).slot'), '투구');
assert.equal(run('game.inventory.find(item=>item.id===oldId).locked'), true);
assert.equal(run('JSON.stringify(game.inventory.find(item=>item.id===oldId).stats)===originalAffixes'), true);
assert.equal(run('game.inventory.find(item=>item.id===oldId).legacyRequirementGrace'), undefined);
assert.ok(run("game.uniqueCodex['투구|타락각 투구']"));
assert.equal(run("game.uniqueCodex['장갑|타락각 투구']"), undefined);
assert.deepEqual(json('game.uniqueHuntTargets'), ['무기|핏빛 톱날']);
const once = json('game.inventory.find(item=>item.id===oldId)');
run('game=mergeDefaults(JSON.parse(JSON.stringify(game)))');
assert.equal(run('game.inventory.filter(item=>item.id===oldId).length'), 1);
assert.deepEqual(json('game.inventory.find(item=>item.id===oldId)'), once);
assert.equal(run("game.uniqueCodex['투구|타락각 투구'].slot"), '투구');
run(`game.blackMarket.offers=[{type:'unique',name:'핏빛 톱날',slot:'장갑',baseId:'hide_gloves',price:7}];
    game.blackMarket.lockedOffers={0:true};normalizeBlackMarketState();`);
assert.equal(run('game.blackMarket.offers[0].slot'), '무기');
assert.equal(run('game.blackMarket.offers[0].price'), 7);
assert.equal(run('game.blackMarket.lockedOffers[0]'), true);
run(`var stashItem=JSON.parse(JSON.stringify(old)), altarItem=JSON.parse(JSON.stringify(old));
    stashItem.id=991;altarItem.id=992;delete stashItem.instanceId;delete altarItem.instanceId;
    var packed=JSON.parse(JSON.stringify(defaultGame));
    packed.inventory=Array.from({length:150},()=>createItemFromBase(BASE_ITEM_DB[0],'normal',1));
    packed.offlineProgress.protectedOverflow=[stashItem];packed.timeRift.altarUnique=altarItem;
    game=mergeDefaults(packed);`);
assert.equal(run('game.inventory.length + game.equipmentTemporaryStorage.length'), 151, 'overflow recovery must not discard owned gear');
assert.equal(run("[...game.inventory,...game.equipmentTemporaryStorage].find(item=>item.id===991).slot"), '투구');
assert.equal(run('game.timeRift.altarUnique.slot'), '투구');
// A migrated implicit keeps exceptional roll quality, affixes, and identity without consuming RNG.
run(`var migrateMe=JSON.parse(JSON.stringify(old));migrateMe.id=993;
    migrateMe.baseStats=[{id:'flatHp',val:144,valMin:80,valMax:120,exceptional:true,originalVal:120}];`);
const rng = runtime.Math.random;
try {
    runtime.Math.random = () => { throw new Error('migration must not roll'); };
    run('normalizeItem(migrateMe)');
} finally { runtime.Math.random = rng; }
assert.equal(run('migrateMe.baseStats[0].val'), run('Math.floor(migrateMe.baseStats[0].valMax*1.2)'));
assert.equal(run('migrateMe.baseStats[0].exceptional'), true);
assert.equal(run('migrateMe.baseStats[0].originalVal'), run('migrateMe.baseStats[0].valMax'));
run(`var normalCopy={...a,rarity:'rare'};`);
assert.notDeepEqual(json('levelProgression.requirements(normalCopy)'), json('levelProgression.requirements(a)'));
// Fixed drop identity must not undo a paid, deliberate base upgrade on the next load.
run(`game=JSON.parse(JSON.stringify(defaultGame));
    var starter=generateUniqueItem(1,null,'첫 계약');game.inventory=[starter];
    var nextBase=getBaseUpgradeCandidates(BASE_ITEM_DB.find(base=>base.id===starter.baseId))[0];
    game.pendingBaseUpgrade={itemId:starter.id,nextBaseId:nextBase.id};
    game.currencies.formlessDew=1000;game.currencies.goldenRule=1000;
    confirmSelectedItemBaseUpgrade();
    var upgradedId=starter.baseId;game=mergeDefaults(JSON.parse(JSON.stringify(game)));`);
assert.equal(run('game.inventory[0].baseId'), run('upgradedId'));
assert.notEqual(run('upgradedId'), 'apprentice_familiar_wand');
assert.ok(run('levelProgression.requirements(game.inventory[0]).level') > 1);
run(`var legacyUpgrade=JSON.parse(JSON.stringify(game));delete legacyUpgrade.inventory[0].uniqueEquipmentVersion;
    game=mergeDefaults(legacyUpgrade);`);
assert.equal(run('game.inventory[0].baseId'), run('upgradedId'), 'identifiable old paid upgrades also survive');
console.log('smoke-unique-equipment-rules passed');
